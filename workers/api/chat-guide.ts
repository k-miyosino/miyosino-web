import { SITE_PAGES, SitePage } from '../../src/shared/constants/sitePages';

function pageLine(page: SitePage): string {
  return `- ${page.names[0]}（${page.path}）: ${page.description}`;
}

const PUBLIC_PAGE_LIST = SITE_PAGES.filter((p) => p.visibility === 'public')
  .map(pageLine)
  .join('\n');
const MEMBER_PAGE_LIST = SITE_PAGES.filter((p) => p.visibility === 'member')
  .map(pageLine)
  .join('\n');

